test('billing currency locks at first activation and survives address-flavored re-resolution', { skip: !HAVE_PGLITE }, async () => {
  await db.exec('TRUNCATE tenants, projects, services, pro_subscriptions;');
  await db.exec(`INSERT INTO tenants(id,plan) VALUES (1,'max');
    CREATE TABLE IF NOT EXISTS users (id INT PRIMARY KEY, tenant_id INT, gstin TEXT, billing_address JSONB);`);
  // No lock yet + no India signal → USD.
  assert.equal(await containerBilling.billingCurrencyFor(1), 'USD');
  // Lock INR (as verifyProSubscription does from the paid base row) → INR wins from then on,
  // even though the users table would still say "not India".
  await containerBilling.lockBillingCurrency(1, 'INR');
  assert.equal(await containerBilling.billingCurrencyFor(1), 'INR');
  // Idempotent + never overwrites: a later USD lock attempt is a no-op.
  await containerBilling.lockBillingCurrency(1, 'USD');
  assert.equal(await containerBilling.billingCurrencyFor(1), 'INR');
});
