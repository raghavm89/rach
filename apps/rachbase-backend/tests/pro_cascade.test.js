test('EVERY paid base charge enqueues the site resume — halt recovery, routine renewal alike (audit #3 F1)', { skip: !HAVE_PGLITE }, async () => {
  await reset();
  // A routine renewal ALSO enqueues the (idempotent, site-side no-op) resume: deriving it
  // from wasHalted missed unsubscribe→re-subscribe, replaced halted rows, and the
  // crash-after-setStatus retry — leaving paying customers at 0 replicas forever.
  await P.handleWebhook({ razorpaySubId: 'sub_base', event: 'charged', paymentId: 'pay_r1', amountMinor: 3000, currency: 'USD' });
  assert.equal(siteOps.resume.length, 1);
  // Halt, then the retried charge lands → resume again, workloads back.
  await P.handleWebhook({ razorpaySubId: 'sub_base', event: 'halted' });
  await P.handleWebhook({ razorpaySubId: 'sub_base', event: 'charged', paymentId: 'pay_r2', amountMinor: 3000, currency: 'USD' });
  assert.equal(siteOps.resume.length, 2);
  assert.equal(siteOps.resume[1].tid, 1);
  assert.equal(await plan(), 'pro'); // gate reopened alongside the site resume
});

