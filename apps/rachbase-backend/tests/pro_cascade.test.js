test('upgrade promotion skips abandoned checkouts and already-waived rows (audit #3 F5)', { skip: !HAVE_PGLITE }, async () => {
  await db.exec('TRUNCATE tenants, projects, services, pro_subscriptions;');
  await db.exec(`
    INSERT INTO tenants(id,plan) VALUES (1,'starter');
    INSERT INTO projects(id,tenant_id) VALUES (1,1);
    INSERT INTO services(id,project_id,name,status,compute_target,compute_size,units) VALUES
      (1,1,'app','online','shared','nano',1),
      (2,1,'ghost','pending_payment','shared','nano',1),
      (3,1,'waived','online','shared','micro',1),
      (4,1,'paying','online','shared','micro',1);
    INSERT INTO pro_subscriptions(id,tenant_id,service_id,kind,razorpay_sub_id,razorpay_plan_id,amount_cents,currency,compute_size,tier,status,created_by) VALUES
      (1,1,NULL,'base','sub_base','plan_base',1000,'USD','nano','starter','active',7),
      (2,1,2,'container','sub_ghost','plan_g',1000,'USD','nano',NULL,'created',7),
      (3,1,3,'container','sub_waived','plan_w',1000,'USD','micro',NULL,'active',7),
      (4,1,4,'container','sub_paying','plan_p',2000,'USD','micro',NULL,'active',7);
    ALTER TABLE pro_subscriptions ALTER COLUMN id RESTART WITH 100;
  `);
  // Row 2 = abandoned checkout (oldest); row 3 = compute-only micro (fee already waived —
  // billable micro would be 2000); row 4 = the genuinely fee-paying container.
  for (const k of Object.keys(calls)) calls[k].length = 0;
  const out = await P.beginProBase({ tenantId: 1, tier: 'pro', currency: 'USD', userId: 7 });
  assert.equal(out.upgraded, true);
  assert.equal(out.promotedContainers, 1);           // ONLY the fee-paying row qualifies
  // The paying micro container is repriced to compute-only ($10) on its own mandate…
  const paying = (await db.query(`SELECT * FROM pro_subscriptions WHERE id=4`)).rows[0];
  assert.equal(paying.amount_cents, 1000);
  assert.ok(calls.update.some((u) => u.id === 'sub_paying'));
  // …while the abandoned checkout and the already-waived row are untouched.
  assert.equal((await db.query(`SELECT status FROM pro_subscriptions WHERE id=2`)).rows[0].status, 'created');
  assert.equal((await db.query(`SELECT amount_cents FROM pro_subscriptions WHERE id=3`)).rows[0].amount_cents, 1000);
  assert.ok(!calls.cancel.includes('sub_ghost'));
  assert.ok(!calls.update.some((u) => u.id === 'sub_waived'));
});

// ── Tier upgrade in place (audit H4: the Starter→Pro no-op) + currency lock (M1) ─────────

const containerBilling = require('../src/services/containerBilling');

// Starter tenant: base $10, container A free (no sub), containers B (micro, $20 sub) and
// C (nano, $10 sub) billable. Upgrading to Pro (3 included) must reprice the base and
// promote B → compute-only ($10) and C → free (sub cancelled).
async function seedStarterWithBillables() {
  await db.exec('TRUNCATE tenants, projects, services, pro_subscriptions;');
  await db.exec(`
    INSERT INTO tenants(id,plan) VALUES (1,'starter');
    INSERT INTO projects(id,tenant_id) VALUES (1,1);
    INSERT INTO services(id,project_id,name,status,compute_target,compute_size,units) VALUES
      (1,1,'app','online','shared','nano',1),
      (2,1,'db','online','shared','micro',1),
      (3,1,'cache','online','shared','nano',1);
    INSERT INTO pro_subscriptions(id,tenant_id,service_id,kind,razorpay_sub_id,razorpay_plan_id,amount_cents,currency,compute_size,tier,status,created_by) VALUES
      (1,1,NULL,'base','sub_base','plan_base',1000,'USD','nano','starter','active',7),
      (2,1,2,'container','sub_c2','plan_c2',2000,'USD','micro',NULL,'active',7),
      (3,1,3,'container','sub_c3','plan_c3',1000,'USD','nano',NULL,'active',7);
    ALTER TABLE pro_subscriptions ALTER COLUMN id RESTART WITH 100;
  `);
  for (const k of Object.keys(calls)) calls[k].length = 0;
}

test('upgrade starter→pro: base repriced, tier recorded, billables promoted into the new allowance', { skip: !HAVE_PGLITE }, async () => {
  await seedStarterWithBillables();
  const out = await P.beginProBase({ tenantId: 1, tier: 'pro', currency: 'USD', userId: 7 });
  assert.equal(out.upgraded, true);
  assert.equal(out.tier, 'pro');
  assert.equal(out.subtotalCents, 3000);        // pro base (USD, ex-GST)
  assert.equal(out.promotedContainers, 2);      // both billables moved into the +2 slots

  const base = (await db.query(`SELECT * FROM pro_subscriptions WHERE kind='base'`)).rows[0];
  assert.equal(base.tier, 'pro');
  assert.equal(base.amount_cents, 3000);
  assert.equal(base.razorpay_sub_id, 'sub_base'); // mandate reused — same subscription
  assert.equal(await plan(), 'pro');

  // Oldest billable (micro) → fee waived, compute-only $10 recurring on the SAME mandate.
  const c2 = (await db.query(`SELECT * FROM pro_subscriptions WHERE id=2`)).rows[0];
  assert.equal(c2.status, 'active');
  assert.equal(c2.amount_cents, 1000);
  assert.ok(calls.update.some((u) => u.id === 'sub_c2'));
  // Next billable (nano) → wholly free: its subscription is cancelled outright.
  const c3 = (await db.query(`SELECT * FROM pro_subscriptions WHERE id=3`)).rows[0];
  assert.equal(c3.status, 'cancelled');
  assert.ok(calls.cancel.includes('sub_c3'));
  // The base itself was repriced via subscriptions.update too (no new checkout).
  assert.ok(calls.update.some((u) => u.id === 'sub_base'));
  assert.equal(calls.create.length, 0); // and NO new subscription was created
});

